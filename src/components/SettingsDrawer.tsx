import React from 'react';
import { WorkflowConfig } from '../types';
import { 
  X, 
  Sliders, 
  ShieldCheck, 
  BookOpen, 
  Check, 
  HelpCircle,
  FileCheck2,
  Sparkles
} from 'lucide-react';

interface SettingsDrawerProps {
  isOpen: boolean;
  onClose: () => void;
  config: WorkflowConfig;
  onUpdateConfig: (config: WorkflowConfig) => void;
}

export const SettingsDrawer: React.FC<SettingsDrawerProps> = ({
  isOpen,
  onClose,
  config,
  onUpdateConfig,
}) => {
  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 bg-slate-900/60 backdrop-blur-xs flex justify-end">
      <div className="bg-white w-full max-w-md h-full shadow-2xl flex flex-col justify-between overflow-y-auto border-l border-slate-200">
        
        {/* Header */}
        <div className="p-5 border-b border-slate-200 flex items-center justify-between bg-slate-50">
          <div className="flex items-center gap-2.5">
            <div className="p-2 bg-red-100 text-red-700 rounded-xl">
              <Sliders className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-sm font-bold text-slate-900">Workflow Rules &amp; Consistency</h3>
              <p className="text-xs text-slate-500">Tune AI summarization parameters</p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-slate-600 rounded-lg hover:bg-slate-200 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content */}
        <div className="p-6 space-y-6 flex-1 text-xs">
          
          {/* Audience Level */}
          <div>
            <label className="block text-xs font-bold text-slate-800 mb-2">
              Audience Level (Constraint: Student-Friendly)
            </label>
            <div className="grid grid-cols-1 gap-2">
              {[
                {
                  id: 'student-friendly',
                  title: 'Student-Friendly (Recommended)',
                  desc: 'Concise, clear, plain-English explanations with analogies & jargon busters.',
                },
                {
                  id: 'undergraduate',
                  title: 'Undergraduate Researcher',
                  desc: 'Academic tone, balanced financial metrics, and deeper analytical depth.',
                },
                {
                  id: 'executive',
                  title: 'Executive Brief',
                  desc: 'High-level strategic bullet points focused on market impact and risks.',
                },
              ].map((lvl) => (
                <button
                  key={lvl.id}
                  onClick={() =>
                    onUpdateConfig({
                      ...config,
                      audienceLevel: lvl.id as any,
                    })
                  }
                  className={`p-3 rounded-xl border text-left transition-all ${
                    config.audienceLevel === lvl.id
                      ? 'border-red-600 bg-red-50/50 ring-1 ring-red-600'
                      : 'border-slate-200 hover:border-slate-300 bg-white'
                  }`}
                >
                  <div className="font-semibold text-slate-900 flex items-center justify-between">
                    <span>{lvl.title}</span>
                    {config.audienceLevel === lvl.id && (
                      <Check className="w-4 h-4 text-red-600" />
                    )}
                  </div>
                  <div className="text-[11px] text-slate-500 mt-0.5">{lvl.desc}</div>
                </button>
              ))}
            </div>
          </div>

          {/* Enforced Structure Template */}
          <div className="p-4 bg-slate-50 rounded-2xl border border-slate-200">
            <div className="flex items-center gap-1.5 font-bold text-slate-900 mb-2">
              <FileCheck2 className="w-4 h-4 text-emerald-600" />
              <span>Consistency Template Enforced</span>
            </div>
            <p className="text-[11px] text-slate-600 mb-3 leading-relaxed">
              Every summary generated by the AI automatically follows this exact schema to ensure standard team comparability:
            </p>
            <ol className="list-decimal list-inside space-y-1 text-[11px] font-medium text-slate-700 bg-white p-2.5 rounded-lg border border-slate-200">
              <li>Article Title &amp; Source Metadata</li>
              <li>Main Idea (1-2 sentences)</li>
              <li>Supporting Points &amp; Evidence (3-4 bullets)</li>
              <li>Key Takeaways &amp; Research Implications</li>
              <li>Student Jargon Buster (Key terms simplified)</li>
            </ol>
          </div>

          {/* Component Toggles */}
          <div className="space-y-3">
            <label className="block text-xs font-bold text-slate-800">
              Summary Modules
            </label>

            <label className="flex items-center justify-between p-3 bg-white border border-slate-200 rounded-xl cursor-pointer hover:bg-slate-50 transition-colors">
              <div className="flex items-center gap-2">
                <HelpCircle className="w-4 h-4 text-amber-500" />
                <div>
                  <div className="font-semibold text-slate-800">Student Jargon Buster</div>
                  <div className="text-[11px] text-slate-500">Defines financial terms like RPO, Capex, and PPA</div>
                </div>
              </div>
              <input
                type="checkbox"
                checked={config.includeGlossary}
                onChange={(e) =>
                  onUpdateConfig({ ...config, includeGlossary: e.target.checked })
                }
                className="rounded border-slate-300 text-red-600 focus:ring-red-500 cursor-pointer"
              />
            </label>

            <label className="flex items-center justify-between p-3 bg-white border border-slate-200 rounded-xl cursor-pointer hover:bg-slate-50 transition-colors">
              <div className="flex items-center gap-2">
                <BookOpen className="w-4 h-4 text-emerald-600" />
                <div>
                  <div className="font-semibold text-slate-800">Actionable Key Takeaways</div>
                  <div className="text-[11px] text-slate-500">Practical conclusions for research projects</div>
                </div>
              </div>
              <input
                type="checkbox"
                checked={config.includeTakeaways}
                onChange={(e) =>
                  onUpdateConfig({ ...config, includeTakeaways: e.target.checked })
                }
                className="rounded border-slate-300 text-red-600 focus:ring-red-500 cursor-pointer"
              />
            </label>
          </div>

          {/* Custom Focus Instructions */}
          <div>
            <label className="block text-xs font-bold text-slate-800 mb-1">
              Custom Prompt Focus (Optional)
            </label>
            <textarea
              rows={3}
              value={config.customFocusInstruction}
              onChange={(e) =>
                onUpdateConfig({
                  ...config,
                  customFocusInstruction: e.target.value,
                })
              }
              placeholder="e.g. Highlight competition with Microsoft and Amazon, and flag any mentions of AI chips or energy grid demands."
              className="w-full p-2.5 border border-slate-300 rounded-xl focus:ring-2 focus:ring-red-500 focus:outline-none text-xs"
            />
          </div>

          {/* Privacy & Security Guarantee */}
          <div className="p-3.5 bg-emerald-50 rounded-xl border border-emerald-200 flex items-start gap-2.5">
            <ShieldCheck className="w-4 h-4 text-emerald-600 shrink-0 mt-0.5" />
            <div className="text-[11px] text-emerald-900 leading-relaxed">
              <strong>Constraint Guarantee:</strong> Sensitive article notes and research materials remain private to this tool session. No data is shared with third parties or persistent public logs.
            </div>
          </div>

        </div>

        {/* Footer */}
        <div className="p-4 border-t border-slate-200 bg-slate-50 flex justify-end">
          <button
            onClick={onClose}
            className="w-full py-2.5 px-4 text-xs font-semibold bg-red-600 hover:bg-red-700 text-white rounded-xl shadow-xs transition-colors"
          >
            Apply &amp; Close Settings
          </button>
        </div>

      </div>
    </div>
  );
};
